    private val byId: Map<String, Exercise> = all.associateBy { it.id }

    fun get(id: String): Exercise? = byId[id]

    /** Alle øvelser som kan gjøres med utstyret brukeren har. Kroppsvekt er alltid med. */
    fun available(equipment: Set<Equipment>): List<Exercise> {
        val owned = equipment + Equipment.BODYWEIGHT
        return all.filter { ex ->
            owned.containsAll(ex.requiresAll) &&
                (ex.requiresAny.isEmpty() || ex.requiresAny.any { it in owned })
        }
    }
